/**
 * Claude mascot animations as flat rectangle data.
 *
 * GENERATED from the SVGs in docs/mascot/ — do not hand-edit; regenerate from source.
 *
 * Each animation is a set of LAYERS, not a flat list of frames, and getting that wrong
 * silently drops content: the confetti lives in two sibling layers OUTSIDE the mascot's
 * own frames, and the flag is a 12-frame sequence inside an otherwise static scene.
 * Composite frame i is every static rect plus frame i of each sequence.
 *
 * Colours are baked here, tinted to a green monochrome that preserves each source
 * colour's relative LUMINANCE, with a floor well above the panel background — an
 * earlier version mapped luminance onto a range starting at the background and the
 * mid-tone dumbbells vanished into it.
 *
 * Coordinates are normalised 0..1 against the union bounding box of every frame in a
 * clip, never per frame: the poses differ in size, and per-frame normalising would
 * rescale the figure each frame so it pulsed as it moved.
 */
